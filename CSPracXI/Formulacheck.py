import math
x = float(input("Enter the value of x: "))
y = float(input("Enter the value of y: "))
z = float(input("Enter the value of z: "))
result = 4 * x**4 + 3 * y**3 + 9 * z + 6 * math.pi
print(f"The result of the expression 4x⁴+3y³+9z+6π is: {result}")
